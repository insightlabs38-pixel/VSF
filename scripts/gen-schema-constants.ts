import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse, sha256Hex, toCanonical } from "../frontend/packages/schema/src/canon.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const schemaPath = join(root, "schemas/smoke/envelope.schema.json");
const schema = parse(readFileSync(schemaPath));
if (!(schema instanceof Map)) throw new Error("schema must be an object");
const name = schema.get("schema_name") as string;
const version = schema.get("version") as string;
const digest = `sha256:${await sha256Hex(toCanonical(schema))}`;
const banner = "generated by scripts/gen-schema-constants.ts from schemas/smoke/envelope.schema.json";

const patternDoc = parse(readFileSync(join(root, "schemas/redaction/patterns.v1.json")));
const patternList = (patternDoc as Map<string, unknown>).get("patterns") as Map<string, string>[];
const patternLines = patternList
  .map(
    (p) =>
      `  { kind: ${JSON.stringify(p.get("kind"))}, source: ${JSON.stringify(p.get("regex"))}, flags: ${JSON.stringify(p.get("flags") ?? "")} },`,
  )
  .join("\n");

const outputs: Record<string, string> = {
  "frontend/packages/observer/src/generated.ts": `// generated by scripts/gen-schema-constants.ts from schemas/redaction/patterns.v1.json
export const REDACTION_PATTERNS: readonly { kind: string; source: string; flags: string }[] = [
${patternLines}
];
`,
  "compiler/crates/vsf-schema/src/generated.rs": `// ${banner}
pub const SCHEMA_NAME: &str = "${name}";
pub const CURRENT_VERSION: &str = "${version}";
pub const KNOWN_VERSIONS: &[(&str, &str)] = &[("${version}", "${digest}")];
`,
  "frontend/packages/schema/src/generated.ts": `// ${banner}
export const SCHEMA_NAME = "${name}";
export const CURRENT_VERSION = "${version}";
export const KNOWN_VERSIONS: readonly (readonly [string, string])[] = [["${version}", "${digest}"]];
`,
  "backend/schema/generated.go": `// ${banner}
package schema

const SchemaName = "${name}"
const CurrentVersion = "${version}"

var KnownVersions = [][2]string{{"${version}", "${digest}"}}
`,
};

let drift = 0;
for (const [rel, body] of Object.entries(outputs)) {
  const path = join(root, rel);
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = "";
  }
  if (current === body) continue;
  if (check) {
    console.error(`drift: ${rel}`);
    drift++;
  } else {
    writeFileSync(path, body);
    console.log(`wrote ${rel}`);
  }
}
if (drift > 0) process.exit(1);
